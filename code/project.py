"""#**Feature Selection**"""

#identify the most important features using random forest classifier
le = LabelEncoder()

# Apply label encoding
df['label_target'] = le.fit_transform(df['target'])
X = df.drop(['target', 'label_target'], axis=1)
y = df['label_target']
mi_scores = mutual_info_classif(X, y, discrete_features='auto', random_state=42)

# Convert to Series and sort
mi_series = pd.Series(mi_scores, index=X.columns).sort_values(ascending=False)

important_features = mi_series[mi_series > 0.001].index.tolist()
print(f'features used for creating model:{len(important_features)}')

"""Cluster the dataset using DB scan so that different model can be created for different cluster"""

df_copy=df[important_features+['target','label_target']]
X=df_copy.drop(['target','label_target'],axis=1)

"""#**Clustering The Data**"""

#Identify the optimal epsilon value

# Set min_samples (e.g., 5 or 10)
min_samples = 10

# Fit nearest neighbors to find k-distance (k = min_samples)
neighbors = NearestNeighbors(n_neighbors=min_samples)
neighbors_fit = neighbors.fit(X)
distances, indices = neighbors_fit.kneighbors(X)

# Sort distances to get the k-distance graph
distances = np.sort(distances[:, min_samples-1], axis=0)

# Plot the k-distance graph to find the "elbow"
plt.figure(figsize=(8, 6))
plt.plot(distances)
plt.title('K-Distance Graph')
plt.xlabel('Points')
plt.ylabel(f'{min_samples}-th Nearest Neighbor Distance')
plt.show()

#setting the epsilon value as 50 and performing DBScan
X_scaled = StandardScaler().fit_transform(X)
dbscan = DBSCAN(eps=15, min_samples=10)
clusters_scaled = dbscan.fit_predict(X_scaled)
print(f"Number of clusters: {len(set(clusters_scaled))}")

"""Since the dataset is clustered into 5 parts, creating different model for different clusters"""

df_copy['cluster']=clusters_scaled

models =defaultdict(dict)

# Loop through each cluster
for cluster in df_copy['cluster'].unique():
    # Filter data for current cluster
    cluster_data = df_copy[df_copy['cluster'] == cluster]

    # Define features and target
    X_cluster = cluster_data.drop(['label_target','target', 'cluster'], axis=1)
    y_cluster = cluster_data['label_target']

    # Apply SMOTE to balance the dataset
    try:
      smote = SMOTE(random_state=42)
      X_resampled, y_resampled = smote.fit_resample(X_cluster, y_cluster)
    except ValueError as e:
        pass

    print("Before resampling:")
    print(y_cluster.value_counts())
    # After resampling (SMOTE)
    print("After resampling:")
    print(pd.Series(y_resampled).value_counts())

    # Split the resampled data
    X_train, X_test, y_train, y_test = train_test_split(X_resampled, y_resampled, test_size=0.2, random_state=42, stratify=y_resampled)

    # Train classifier
    model = RandomForestClassifier(random_state=42)
    model.fit(X_train, y_train)

    # Predict and evaluate
    y_pred = model.predict(X_test)
    accuracy = accuracy_score(y_test, y_pred)
    recall = recall_score(y_test, y_pred, average='macro')
    models[cluster]['recall'] = recall
    print(f"Cluster {cluster} - Accuracy after SMOTE: {accuracy:.4f}")
    print(f"Cluster {cluster} - Recall after SMOTE: {recall:.4f}")
    # Store model and SMOTE-balanced data if needed
    models[cluster]['model'] = model
    models[cluster]['accuracy'] = accuracy

print(models)

"""#**Model Explainability**"""

