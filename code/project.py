"""#**Feature Engineering**"""

#Applying one hot encoding on categorical features
categorical_columns = df.select_dtypes(include=['object', 'category']).columns.tolist()

# Ensure target column is excluded from encoding
categorical_columns = [col for col in categorical_columns if col != 'target']

# Step 2: Apply one-hot encoding
df_encoded = pd.get_dummies(df, columns=categorical_columns, drop_first=True)
boolean_columns = df_encoded.select_dtypes(include=['bool']).columns.tolist()
